// Builds the film data from the real result files (no network at render time).
//   in:  ../prototypes/hollow-twin-poc/public/results/scenarios.json   (held-out numbers, 95% intervals)
//        assets/footage/<id>.json                                       (the shown seed, day by day)
//   out: assets/data.js   window.FILM_DATA[id] = { points, days, ... }  (the counters read it by timeline time)
//        rows.json        one batch row per disaster for `render --batch`
// Run: node build-data.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const HERE = new URL('.', import.meta.url);
const res = JSON.parse(readFileSync(new URL('../prototypes/hollow-twin-poc/public/results/scenarios.json', HERE), 'utf8'));

// Short titles and the one event line per disaster (the same display names as the site).
const META = {
  twoplants: { title: 'Two plants lost at once', event: 'Plants 4 and 5 lose output', src: 'EIA-930, TVA and CPLE coal, Dec 2022' },
  elliott: { title: 'Plant loss, Winter Storm Elliott', event: 'Plant 4 loses output', src: 'EIA-930, TVA coal, Dec 2022' },
  cascade: { title: 'Plant loss, Texas, Feb 2021', event: 'Plant 2 loses output', src: 'EIA-930, ERCOT generation, Feb 2021' },
  slowloss: { title: 'Slow two-week plant loss', event: 'Plant 6 loses output for two weeks', src: 'EIA-930, SPP wind, Feb 2021' },
  aging: { title: 'Aging plants', event: 'Every plant wears out (4 real years in 120 days)', src: 'The Geysers decline, Foulger et al. 1997' },
  crowding: { title: 'Crowding', event: 'Sections grow (4 real years in 120 days)', src: 'Census county growth 2020–2024' },
  baseline: { title: 'Baseline', event: 'Normal weekly demand, no extra failure', src: 'EIA-930, ERCOT demand, 2023' },
};
const EVENT_DAY = { twoplants: 5, elliott: 5, cascade: 5, slowloss: 5, aging: 1, crowding: 1, baseline: 1 };

const fmt = (x) => Math.round(x).toLocaleString('en-US');
const data = {};
const rows = [];
for (const s of res.scenarios) {
  const meta = META[s.id] ?? { title: s.name, event: s.summary };
  const fp = new URL(`assets/footage/${s.id}.json`, HERE);
  const track = existsSync(fp) ? JSON.parse(readFileSync(fp, 'utf8')) : null;
  data[s.id] = {
    days: track?.days ?? 30,
    seed: track?.seed ?? null,
    points: track?.points ?? [],
  };
  rows.push({
    name: s.id,
    scenario: s.id,
    title: meta.title,
    footage: `assets/footage/${s.id}.mp4`,
    event: meta.event,
    eventDay: EVENT_DAY[s.id] ?? 1,
    endWithout: fmt(s.without.deaths.mean),
    endWith: fmt(s.with.deaths.mean),
    endNote: `Mean deaths per run, held-out seeds ${res.seeds[0]}–${res.seeds[res.seeds.length - 1]}.`,
    source: meta.src ?? s.realData,
  });
}
writeFileSync(new URL('assets/data.js', HERE), `// Generated by build-data.mjs. Do not edit.\nwindow.FILM_DATA = ${JSON.stringify(data)};\n`);
writeFileSync(new URL('rows.json', HERE), JSON.stringify({ rows }, null, 2) + '\n');
console.log(`Wrote assets/data.js and rows.json for ${rows.length} disasters (${rows.filter((r) => data[r.scenario].points.length).length} with footage tracks).`);
